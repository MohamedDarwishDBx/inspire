import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// Puts bootGuard.js inline ahead of the app's module script in every page's <head>, so it runs even when the module graph fails.
// Inline on purpose: the hosted App shell sends a script-src that allows only its own assets, so the page's CSP lists the
// hash of this exact text (BOOT_GUARD_SCRIPT_HASH). The build writes that hash to backend/lib/bootGuardCsp.js, which the
// backend's CSP builders read. Vite never minifies this script (checked by shared/test/bootGuardHash.test.mjs).
const GUARD = readFileSync(fileURLToPath(new URL('./bootGuard.js', import.meta.url)), 'utf8');
if (GUARD.includes('</script')) throw new Error('bootGuard.js must not contain a closing script tag');
// The text between <script> and </script> is "\n" + GUARD.
export const BOOT_GUARD_SCRIPT_HASH = `sha256-${createHash('sha256').update(`\n${GUARD}`).digest('base64')}`;
const CSP_MODULE = fileURLToPath(new URL('../backend/lib/bootGuardCsp.js', import.meta.url));

export default function bootGuard() {
  return {
    name: 'inspire-boot-guard',
    closeBundle: { order: 'post', handler() {
      writeFileSync(CSP_MODULE, `// Generated by app/shared/bootGuardPlugin.mjs from app/shared/bootGuard.js on every frontend and App shell build. Do not edit.\n`
        + `module.exports = { BOOT_GUARD_SCRIPT_HASH: '${BOOT_GUARD_SCRIPT_HASH}' };\n`);
    } },
    transformIndexHtml: {
      order: 'pre',
      handler: (html) => html.replace(/<head>/i, () => `<head>\n    <script>\n${GUARD}</script>`),
    },
  };
}
